/* ==========================================================================
 * 文件：Core/Src/main.c
 * 芯片：CH32V003F4P6（RISC-V RV32EC，16K Flash / 2K RAM）
 * 库  ：WCH CH32V00x 外设库（vendored，来自 openwch/ch32v003 EVT）
 * 功能：最小工程模板：PD0 推挽输出，500 ms 翻转一次
 * 时钟：HSI 24MHz × PLL2 = 48MHz（system_ch32v00x.c 中配置）
 * ==========================================================================
 *                        业务代码放置地图
 * --------------------------------------------------------------------------
 *  ① 引脚 / 硬件宏定义          -> 第 1 区
 *  ② 自己的函数声明             -> 第 2 区
 *  ③ 外设初始化（只执行一次）    -> main() 3.1 区
 *  ④ 主循环周期业务             -> main() 3.2 区
 *  ⑤ 业务函数的具体实现          -> 文件末尾第 4 区
 *  ⑥ 中断服务函数               -> Core/Src/ch32v00x_it.c
 * --------------------------------------------------------------------------
 *  说明：这里刻意使用直接寄存器操作（类似 STM32 LL），不走 GPIO_Init()
 *        StdPeriph 封装，便于和 STM32 LL 工程对照学习。
 * ========================================================================== */

/* ====================================== */
/* 0. 头文件                              */
/* ====================================== */
#include "debug.h"                  /* ch32v00x.h + Delay_Init/Delay_Ms */

/* ====================================== */
/* 1. 板级宏定义：改硬件引脚只改这里        */
/* ====================================== */
#define LED_GPIO            GPIOD           /* LED 所在端口 */
#define LED_PIN             GPIO_Pin_0      /* LED 引脚：PD0 */
#define LED_PIN_NUM         0u              /* 引脚号，用于计算 CFGLR 位域 */

/* 常见 CH32V003F4P6 小板 LED 为低电平点亮；若你的板子是高电平点亮，
 * 把 LED_ON / LED_OFF 两个宏对调即可。 */
#define LED_ON()            (LED_GPIO->OUTDR &= ~LED_PIN)
#define LED_OFF()           (LED_GPIO->OUTDR |=  LED_PIN)
#define LED_TOGGLE()        (LED_GPIO->OUTDR ^=  LED_PIN)

/* 闪烁周期（毫秒） */
#define LED_BLINK_MS        500u

/* ====================================== */
/* 2. 函数声明区                          */
/* ====================================== */
static void LED_Init(void);

/* ====================================== */
/* 3. 主函数：初始化 + 主循环             */
/* ====================================== */
int main(void)
{
    /* ====================================== */
    /* 3.1 外设初始化（只执行一次）            */
    /* ====================================== */
    LED_Init();                     /* PD0 推挽输出，30MHz */
    Delay_Init();                   /* SysTick 延时初始化（基于 48MHz） */

    /* ====================================== */
    /* 3.2 主循环：周期业务                    */
    /* ====================================== */
    while (1)
    {
        LED_TOGGLE();               /* 翻转 PD0 */
        Delay_Ms(LED_BLINK_MS);     /* 500 ms */
    }
}

/* ====================================== */
/* 4. 业务函数实现                        */
/* ====================================== */

/*********************************************************************
 * @fn      LED_Init
 *
 * @brief   配置 PD0 为通用推挽输出，速度 30MHz。
 *          CFGLR 每个引脚占 4 bit：CNF[1:0] + MODE[1:0]
 *          MODE=11(30MHz)，CNF=00(通用推挽输出) -> 0b0011
 *
 * @return  none
 */
static void LED_Init(void)
{
    /* 使能 GPIOD 时钟（APB2） */
    RCC->APB2PCENR |= RCC_APB2Periph_GPIOD;

    /* 清空 PD0 的 4 位配置，再写入 0b0011 */
    LED_GPIO->CFGLR &= ~(0xFu << (LED_PIN_NUM * 4u));
    LED_GPIO->CFGLR |=  (0x3u << (LED_PIN_NUM * 4u));

    /* 默认熄灭（低电平点亮时，输出高 = 灭） */
    LED_OFF();
}
